import assert from 'node:assert/strict';
const events=new Map,children=[];
const reader={hidden:true,append(frame){children.push(frame)}};
const frameWindow={sent:[],postMessage(message,origin){this.sent.push({message,origin})}};
globalThis.document={getElementById:id=>id==='reader'?reader:{value:'US'},createElement:()=>({contentWindow:frameWindow,addEventListener(name,fn){events.set('frame:'+name,fn)},remove(){}})};
globalThis.window={addEventListener:(name,fn)=>events.set(name,fn),MercyAudio:{stop(){}},GuideAppPolicy:{block(){}}};
const {mountCompanionBook}=await import('../guide/international/book.mjs');
let finished=0,changed='';
const credential='sensitive-test-token';
const book=mountCompanionBook({getLanguage:()=> 'ar',getAccess:()=>({credential,invite:null}),onPosition(){},onError(){},onFinish(){finished++},onInstall(){},onLanguage:language=>changed=language});
book.show(Array.from({length:86},(_,i)=>({number:i+1})));
assert.equal(reader.hidden,false);assert.equal(children.length,1);
const frame=children[0],url=new URL(frame.src);assert.equal(url.pathname,'/guide/international/reader/');assert.equal(url.searchParams.get('lang'),'ar');assert.equal(url.searchParams.get('country'),'US');assert.equal(frame.src.includes(credential),false);
await events.get('frame:load')();assert.equal(frameWindow.sent[0].origin,url.origin);assert.equal(frameWindow.sent[0].message.credential,credential);
const message=events.get('message');
message({source:frameWindow,origin:'https://evil.example',data:{type:'GUIDE_READER_FINISH'}});assert.equal(finished,0);
message({source:{},origin:url.origin,data:{type:'GUIDE_READER_FINISH'}});assert.equal(finished,0);
message({source:frameWindow,origin:url.origin,data:{type:'GUIDE_READER_LANGUAGE',language:'ar'}});assert.equal(changed,'ar');
message({source:frameWindow,origin:url.origin,data:{type:'GUIDE_READER_FINISH'}});assert.equal(finished,1);
book.hide();assert.equal(reader.hidden,true);
console.log('International full-book launcher: complete reader, country/language, credential-free URLs, trusted messages and finish controls passed.');
